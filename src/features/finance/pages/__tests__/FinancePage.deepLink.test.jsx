/**
 * Notification deep links on Finance.
 *
 * The bell points at a specific payout request, refund or invoice. Landing on
 * the right tab was never enough: the lists are paginated server-side, so the
 * target is often not on the page that opens. Each link below resolves its row
 * by id, the same way ReviewsPage resolves `?reviewId`.
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';

const {
  fetchFinanceSummaryMock,
  fetchFinanceEarningsMock,
  fetchPayoutRequestsMock,
  fetchPayoutRequestByIdMock,
  fetchPayoutMethodsMock,
  fetchRefundRequestsMock,
  getFinanceChargesMock,
  fetchMyInvoicesMock,
} = vi.hoisted(() => ({
  fetchFinanceSummaryMock: vi.fn(),
  fetchFinanceEarningsMock: vi.fn(),
  fetchPayoutRequestsMock: vi.fn(),
  fetchPayoutRequestByIdMock: vi.fn(),
  fetchPayoutMethodsMock: vi.fn(),
  fetchRefundRequestsMock: vi.fn(),
  getFinanceChargesMock: vi.fn(),
  fetchMyInvoicesMock: vi.fn(),
}));

vi.mock('../../api', () => ({
  fetchFinanceSummary: fetchFinanceSummaryMock,
  fetchFinanceEarnings: fetchFinanceEarningsMock,
  fetchPayoutRequests: fetchPayoutRequestsMock,
  fetchPayoutRequestById: fetchPayoutRequestByIdMock,
  fetchPayoutMethods: fetchPayoutMethodsMock,
  getFinanceCharges: getFinanceChargesMock,
  fetchMyInvoices: fetchMyInvoicesMock,
  cancelPayoutRequest: vi.fn(),
  createPayoutMethod: vi.fn(),
  deletePayoutMethod: vi.fn(),
  createPayoutRequest: vi.fn(),
  createRefundRequest: vi.fn(),
  withdrawRefundRequest: vi.fn(),
  fetchPayoutSettings: vi.fn(),
  fetchPayouts: vi.fn(),
  updatePayoutMethod: vi.fn(),
  updatePayoutSettings: vi.fn(),
}));

vi.mock('@/stores/authStore', () => ({
  getAuthToken: () => 'test-token',
  useAuthStore: () => ({ user: { id: 'u1', name: 'Expedition-Go Tours' } }),
}));

// The refunds tab also loads the supplier's own refund requests; keep that
// call local so the tab's dispute assertions are not affected by real I/O.
vi.mock('@/features/bookings/api', () => ({
  fetchRefundRequests: fetchRefundRequestsMock,
  withdrawRefundRequest: vi.fn(() => Promise.resolve({})),
}));

vi.mock('@/features/refund-claims/pages/RefundClaimsPage', () => ({ default: () => null }));
vi.mock('../../components/PayoutMethodFormSheet', () => ({ default: () => null }));

// The invoices tab owns its own drawer and has its own test; this one asserts
// it is handed the linked invoice at all.
const invoicesTabProps = [];
vi.mock('../../components/InvoicesTab', () => ({
  default: (props) => {
    invoicesTabProps.push(props);
    return <div data-testid="invoices-tab">focus: {props.focusInvoiceId || 'none'}</div>;
  },
}));

vi.mock('@/hooks/useTeamRole', () => ({
  useTeamRole: () => ({ hasPermission: () => true }),
}));

const MOTION_ONLY_PROPS = new Set([
  'initial', 'animate', 'exit', 'transition', 'layoutId', 'layout',
  'variants', 'custom', 'whileHover', 'whileTap', 'onAnimationStart',
]);

vi.mock('framer-motion', () => ({
  motion: new Proxy(
    {},
    {
      get: (_t, tag) => (props) => {
        const domProps = {};
        for (const [key, value] of Object.entries(props || {})) {
          if (!MOTION_ONLY_PROPS.has(key)) domProps[key] = value;
        }
        return typeof tag === 'string' ? React.createElement(tag, domProps) : null;
      },
    }
  ),
  AnimatePresence: ({ children }) => children,
}));

import React from 'react';
import FinancePage from '../FinancePage';

const SUMMARY = {
  availableBalance: { amount: 250, currency: 'USD', bookingCount: 1 },
  pendingClearance: { amount: 0, currency: 'USD', bookingCount: 0, clearanceBufferDays: 0 },
  inReview: { total: 0, byCurrency: {}, requestCount: 0, bookingCount: 0, latestRequest: null },
  paidOut: { total: 0, currency: 'USD' },
  payoutCounts: { PENDING: 0, ELIGIBLE: 1, REQUESTED: 0, PAID: 0, DISPUTED: 0, CANCELLED: 0 },
  nextEligibleAt: null,
  withdrawalWindow: null,
  payoutPlan: null,
};

const payoutRequestRow = (over = {}) => ({
  id: 'pr1',
  requestNumber: 'PR-20261005-000001',
  amount: 120,
  currency: 'USD',
  bookingCount: 3,
  status: 'PROCESSING',
  cycleLabel: 'Sep 28 – Oct 4',
  reference: '',
  createdAt: '2026-10-05T00:26:00.000Z',
  completedAt: null,
  rejectedReason: '',
  autoGenerated: true,
  method: 'Bank transfer',
  ...over,
});


const renderPage = (url) =>
  render(
    <MemoryRouter initialEntries={[url]}>
      <FinancePage />
    </MemoryRouter>
  );

const ready = () => waitFor(() => expect(fetchFinanceSummaryMock).toHaveBeenCalled());

beforeEach(() => {
  vi.clearAllMocks();
  invoicesTabProps.length = 0;
  fetchFinanceSummaryMock.mockResolvedValue(SUMMARY);
  fetchFinanceEarningsMock.mockResolvedValue({ earnings: [], pagination: null });
  fetchPayoutRequestsMock.mockResolvedValue({ requests: [payoutRequestRow()], pagination: null });
  fetchPayoutRequestByIdMock.mockResolvedValue(
    payoutRequestRow({ id: 'pr9', requestNumber: 'PR-20261005-000009' })
  );
  fetchPayoutMethodsMock.mockResolvedValue([]);
  fetchRefundRequestsMock.mockResolvedValue({ requests: [], total: 0, page: 1, limit: 50 });
  getFinanceChargesMock.mockResolvedValue({ charges: [], openTotals: [] });
  fetchMyInvoicesMock.mockResolvedValue({ invoices: [], pagination: null });
});

describe('a ?payoutRequestId deep link', () => {
  it('fetches the request itself when it is not on the open page', async () => {
    renderPage('/finance?tab=payouts&payoutRequestId=pr9');
    await ready();

    await waitFor(() => expect(fetchPayoutRequestByIdMock).toHaveBeenCalledWith('pr9'));
    // The row is rendered, not just the tab it lives on.
    await waitFor(() => expect(screen.getByText('PR-20261005-000009')).toBeInTheDocument());
  });

  it('does not refetch a request the page already has', async () => {
    renderPage('/finance?tab=payouts&payoutRequestId=pr1');
    await ready();

    await waitFor(() => expect(screen.getByText('PR-20261005-000001')).toBeInTheDocument());
    expect(fetchPayoutRequestByIdMock).not.toHaveBeenCalled();
  });

  it('leaves the tab usable when the request cannot be fetched', async () => {
    fetchPayoutRequestByIdMock.mockRejectedValue(new Error('gone'));
    renderPage('/finance?tab=payouts&payoutRequestId=pr9');
    await ready();

    // The rest of the Payouts tab still renders.
    await waitFor(() => expect(screen.getByText('PR-20261005-000001')).toBeInTheDocument());
  });
});

describe('a ?refundRequestId deep link', () => {
  it('shows the refund request the notification is about, inside the tabbed list', async () => {
    fetchRefundRequestsMock.mockResolvedValue({
      requests: [{
        id: 'sr9',
        requestNumber: 'SR-20261105-E2AD',
        status: 'COMPLETED',
        createdAt: '2026-11-05T13:17:26.909Z',
        decidedAt: '2026-11-05T13:33:35.281Z',
        preview: { proposed: 35, charge: 29.75, currency: 'USD' },
        booking: {
          bookingNumber: 'TRG-45236279-2026-54',
          tourTitle: 'Accra Guided City Tour',
          travelDate: '2026-10-27T00:00:00.000Z',
          grossAmount: 35,
          currency: 'USD',
        },
      }],
      total: 1,
      page: 1,
      limit: 50,
    });

    renderPage('/finance?tab=refunds&refundRequestId=sr9');
    await ready();

    await waitFor(() => expect(screen.getByText('SR-20261105-E2AD')).toBeInTheDocument());
    // It lives in the same list as every other request, under the All tab.
    expect(screen.getByRole('button', { name: 'All' })).toHaveAttribute('aria-pressed', 'true');
    expect(document.getElementById('refund-request-sr9')).toBeInTheDocument();
  });

  it('sends the supplier to a completed booking to file a refund', async () => {
    renderPage('/finance?tab=refunds');
    await ready();
    expect(await screen.findByRole('button', { name: /request a refund/i })).toBeInTheDocument();
  });
});

describe('an ?invoiceId deep link', () => {
  it('is handed to the invoices tab so it can open that invoice', async () => {
    renderPage('/finance?tab=invoices&invoiceId=inv9');
    await ready();

    expect(await screen.findByTestId('invoices-tab')).toHaveTextContent('focus: inv9');
    expect(invoicesTabProps.at(-1).focusInvoiceId).toBe('inv9');
    // Closing the drawer has to be able to drop the param.
    expect(typeof invoicesTabProps.at(-1).onFocusCleared).toBe('function');
  });
});
