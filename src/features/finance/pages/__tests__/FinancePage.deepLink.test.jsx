const renderPage = (url) =>
  render(
    <MemoryRouter initialEntries={[url]}>
      <FinancePage />
    </MemoryRouter>
  );

const ready = () => waitFor(() => expect(fetchFinanceSummaryMock).toHaveBeenCalled());

beforeEach(() => {
  vi.clearAllMocks();
  invoicesTabProps.length = 0;
  fetchFinanceSummaryMock.mockResolvedValue(SUMMARY);
  fetchFinanceEarningsMock.mockResolvedValue({ earnings: [], pagination: null });
  fetchPayoutRequestsMock.mockResolvedValue({ requests: [payoutRequestRow()], pagination: null });
  fetchPayoutRequestByIdMock.mockResolvedValue(
    payoutRequestRow({ id: 'pr9', requestNumber: 'PR-20261005-000009' })
  );
  fetchPayoutMethodsMock.mockResolvedValue([]);
  fetchFinanceDisputesMock.mockResolvedValue({ disputes: [disputeRow()], pagination: null });
  getFinanceChargesMock.mockResolvedValue({ charges: [], openTotals: [] });
  fetchMyInvoicesMock.mockResolvedValue({ invoices: [], pagination: null });
});

describe('a ?payoutRequestId deep link', () => {
  it('fetches the request itself when it is not on the open page', async () => {
    renderPage('/finance?tab=payouts&payoutRequestId=pr9');
    await ready();

    await waitFor(() => expect(fetchPayoutRequestByIdMock).toHaveBeenCalledWith('pr9'));
    // The row is rendered, not just the tab it lives on.
    await waitFor(() => expect(screen.getByText('PR-20261005-000009')).toBeInTheDocument());
  });

  it('does not refetch a request the page already has', async () => {
    renderPage('/finance?tab=payouts&payoutRequestId=pr1');
    await ready();

    await waitFor(() => expect(screen.getByText('PR-20261005-000001')).toBeInTheDocument());
    expect(fetchPayoutRequestByIdMock).not.toHaveBeenCalled();
  });

  it('leaves the tab usable when the request cannot be fetched', async () => {
    fetchPayoutRequestByIdMock.mockRejectedValue(new Error('gone'));
    renderPage('/finance?tab=payouts&payoutRequestId=pr9');
    await ready();

    // The rest of the Payouts tab still renders.
    await waitFor(() => expect(screen.getByText('PR-20261005-000001')).toBeInTheDocument());
  });
});

describe('a ?disputeId deep link', () => {
  it('fetches the refund it names and opens its detail', async () => {
    fetchFinanceDisputesMock.mockImplementation((params = {}) =>
      Promise.resolve(
        params.disputeId
          ? { disputes: [disputeRow({ id: 'dp9', disputeNumber: 'DP-2026-0009' })], pagination: null }
          : { disputes: [disputeRow()], pagination: null }
      )
    );
    renderPage('/finance?tab=refunds&disputeId=dp9');
    await ready();

    await waitFor(() =>
      expect(fetchFinanceDisputesMock).toHaveBeenCalledWith({ disputeId: 'dp9' })
    );
    // Assert inside waitFor rather than via findByText: the row is mounted by
    // an effect after the fetch resolves, so the query and the assertion have
    // to happen in the same render — between two awaits the row can still be
    // mid-mount.
    await waitFor(() => expect(screen.getByText('DP-2026-0009')).toBeInTheDocument());
    // The row expands on click; the link does it for the supplier.
    await waitFor(() => expect(screen.getByText('Booking total')).toBeInTheDocument());
  });

  it('opens a refund already on the page without refetching', async () => {
    renderPage('/finance?tab=refunds&disputeId=dp1');
    await ready();

    await waitFor(() => expect(screen.getByText('Booking total')).toBeInTheDocument());
    expect(fetchFinanceDisputesMock).toHaveBeenCalledTimes(1);
  });
});

describe('an ?invoiceId deep link', () => {
  it('is handed to the invoices tab so it can open that invoice', async () => {
    renderPage('/finance?tab=invoices&invoiceId=inv9');
    await ready();

    expect(await screen.findByTestId('invoices-tab')).toHaveTextContent('focus: inv9');
    expect(invoicesTabProps.at(-1).focusInvoiceId).toBe('inv9');
    // Closing the drawer has to be able to drop the param.
    expect(typeof invoicesTabProps.at(-1).onFocusCleared).toBe('function');
  });
});
