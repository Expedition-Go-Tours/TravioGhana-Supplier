/**
 * Stays finance API — the Stays mirror of `features/finance/api.js`: the same
 * function names and shapes the finance page consumes, backed by the stays
 * mock today and the `/stays/supplier/finance/...` endpoints when the backend
 * ships. Amounts are USD, like the Experiences finance page.
 */
import api from "@/lib/axios";
import { formatCurrency } from "@/lib/utils";
import { staysMock } from "./mock/store";
import { staysUsesMockData } from "./api";

const BASE = "/stays/supplier";
const requestConfig = { skipGlobalErrorHandler: true };

export async function fetchFinanceSummary() {
  if (staysUsesMockData) return staysMock.getFinanceSummary();
  const response = await api.get(`${BASE}/finance/summary`, requestConfig);
  return response.data?.data || {};
}

export async function fetchFinanceEarnings(params = {}) {
  if (staysUsesMockData) return staysMock.getFinanceEarnings(params);
  const response = await api.get(`${BASE}/finance/earnings`, { ...requestConfig, params });
  const payload = response.data?.data || {};
  return {
    earnings: (payload.earnings || []).map((item) => ({
      id: item.id,
      bookingId: item.bookingId,
      bookingNumber: item.bookingNumber,
      travelDate: item.travelDate,
      stayDate: item.travelDate,
      paidAt: item.paidAt,
      grossAmount: Number(item.grossAmount) || 0,
      supplierPayout: Number(item.supplierPayout) || 0,
      commissionAmount: Number(item.platformCommission) || 0,
      commissionRate: Number(item.commissionRate) || 0,
      currency: item.currency || "USD",
      payoutStatus: item.payoutStatus,
      status: item.status,
      property: item.property?.name || "—",
      room: item.room || "—",
      customer: item.customer?.name || "—",
      payoutRequest: item.payoutRequest || null,
      openDispute: item.openDispute || null,
    })),
    summary: payload.summary || {},
    pagination: payload.pagination || null,
  };
}

