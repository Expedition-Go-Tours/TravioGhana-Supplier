export async function getFinanceCharges() {
  if (staysUsesMockData) return staysMock.getFinanceCharges();
  const response = await api.get(`${BASE}/finance/charges`, requestConfig);
  const payload = response.data?.data || {};
  const charges = (payload.charges || []).map((charge) => ({
    id: charge.id,
    amount: Number(charge.amount) || 0,
    currency: charge.currency || "USD",
    reason: charge.reason || "",
    status: charge.status,
    notes: charge.notes || "",
    createdAt: charge.createdAt,
    settledAt: charge.settledAt,
    bookingId: charge.bookingId,
    bookingNumber: charge.bookingNumber || "—",
    payoutRequestId: charge.payoutRequestId,
    payoutRequestNumber: charge.payoutRequestNumber || null,
  }));
  const openTotals = Object.entries(payload.openTotals || {}).map(([currency, amount]) => ({
    currency,
    amount: Number(amount) || 0,
  }));
  return { charges, openTotals };
}

