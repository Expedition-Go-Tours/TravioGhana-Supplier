/* ── Refund claims (the Refund Requests tab) ─────────────────────────────── */

export function mapClaim(claim) {
  const booking = claim?.booking || {};
  return {
    id: claim.id,
    claimNumber: claim.claimNumber,
    reason: claim.reason,
    details: claim.details || "",
    type: claim.type,
    requestedAmount: Number(claim.requestedAmount) || 0,
    status: claim.status,
    createdAt: claim.createdAt,
    reviewNote: claim.reviewNote || null,
    releasedAmount: Number(claim.releasedAmount) || 0,
    booking: {
      bookingNumber: booking.bookingNumber || "",
      total: Number(booking.grossAmount) || 0,
      currency: booking.currency || "USD",
      customerName: booking.customer?.name || "Guest",
      customerEmail: booking.customer?.email || "",
      propertyTitle: booking.property?.name || "",
    },
  };
}

export async function fetchSupplierClaims(status) {
  if (staysUsesMockData) return staysMock.getSupplierClaims(status);
  const response = await api.get(`${BASE}/refund-claims/supplier`, {
    ...requestConfig,
    params: status && status !== "ALL" ? { status } : {},
  });
  return (response.data?.data?.claims || []).map(mapClaim);
}

export async function approveClaim(id) {
  if (staysUsesMockData) return staysMock.approveClaim(id);
  const response = await api.patch(`${BASE}/refund-claims/supplier/${id}/approve`, {}, requestConfig);
  return mapClaim(response.data?.data?.claim);
}

export async function declineClaim(id, note) {
  if (staysUsesMockData) return staysMock.declineClaim(id, note);
  const response = await api.patch(
    `${BASE}/refund-claims/supplier/${id}/decline`,
    { note },
    requestConfig,
  );
  return mapClaim(response.data?.data?.claim);
}

